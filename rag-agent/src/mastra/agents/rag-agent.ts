// ============================================================================
// RAG エージェント（社内ドキュメント検索）— 学習メモ
// ============================================================================
// RAG = Retrieval-Augmented Generation（検索拡張生成）
//   ① 関連文書を「検索して取ってくる」→ ② その内容をもとに LLM が「回答を書く」
//
// このファイルには2つの登場人物がいる。それぞれ役割と使うモデルが違う：
//   - ragTool  … 「検索する道具」   → 埋め込みモデルを使う
//   - ragAgent … 「答える主体（脳）」 → 生成モデル(LLM)を使う
//
// ★ tool と agent の違い ＝「自分で"何をするか"を判断するか（自律性）」
//    - tool  : 決まった1つの仕事をこなすだけ。判断しない（＝今回の ragTool）
//    - agent : どのツールをいつ呼ぶか等を自分で判断し、文章で答える（＝ ragAgent）
//    ※「モデルを使う/使わない」や「安い/高い」は境界ではない。判断の有無が境界。
// ============================================================================

import { Agent } from "@mastra/core/agent";
import { createVectorQueryTool } from "@mastra/rag";
import { ModelRouterEmbeddingModel } from "@mastra/core/llm";
import { LIBSQL_PROMPT } from "@mastra/libsql";

// ----------------------------------------------------------------------------
// ragTool ＝「検索する道具」（tool）
//   役割：ユーザーの質問をベクトル化し、近い意味のチャンクを DB から探して返す。
//   これは「1回まっすぐ検索するだけ」で判断の余地がない → だから agent ではなく tool。
//   （クエリ書き換え・複数回検索・index選択などの"判断"が要るなら agent 化＝agentic RAG）
// ----------------------------------------------------------------------------
const ragTool = createVectorQueryTool({
  // 検索先のベクトルストア。index.ts の vectors:{ libSqlVector } のキーと一致させる。
  vectorStoreName: "libSqlVector",
  // 検索対象の index 名。文書投入(seed)時の upsert の indexName と一致させる。
  indexName: "company_docs",
  // ★ 埋め込みモデル：テキスト→ベクトル(数値)へ変換する専用モデル。文章は書かない。
  //    検索は「意味の近さ」で行うが、同じ入力なら同じベクトル → 基本"決定的"（曖昧だがランダムではない）。
  //    【重要】文書投入(seed)時に使った埋め込みモデルと必ず同じにする。
  //            ズレるとベクトルの意味空間が合わず検索が壊れる。
  model: new ModelRouterEmbeddingModel("google/gemini-embedding-001"),
  // メタデータでの絞り込み検索を有効化（下の LIBSQL_PROMPT とセットで機能する）。
  enableFilter: true,
  description: "社内ドキュメント(FAQ、運用マニュアル、オンボーディングガイド）から関連情報を検索します",
});

// ----------------------------------------------------------------------------
// ragAgent ＝「答える主体」（agent）
//   役割：質問を読んで「ragTool を呼ぼう」と判断 → 検索結果を読んで回答を生成する。
//   処理の流れ：
//     ① 質問が届く
//     ② 生成LLM が「検索が必要」と判断し ragTool を呼ぶ   ← 判断するのは生成LLM
//     ③ ragTool の中で埋め込みモデルが検索を実行
//     ④ ヒットしたチャンク本文が戻る
//     ⑤ 生成LLM がその本文をもとに回答を書く            ← 生成もまた生成LLM
// ----------------------------------------------------------------------------
export const ragAgent = new Agent({
  id: "rag-agent",
  name: "社内ドキュメント検索エージェント",
  // instructions のポイント：
  //   ・「必ず検索ツールを使ってから回答」= 自前の知識で答えず、まず検索させる（RAGの肝）
  //   ・「検索結果のみに基づいて回答」「無ければ正直に無いと言う」= ハルシネーション抑制
  //   ・LIBSQL_PROMPT = enableFilter で使う絞り込みクエリの組み立て方を LLM に教えるお作法
  instructions: `あなたは社内ドキュメントに基づいて質問に回答するアシスタントです。
ユーザーの質問に対して、必ずベクトル検索ツールを使って関連情報を検索してから回答してください。
検索結果に含まれる情報のみに基づいて回答し、情報が見つからない場合はその旨を正直に伝えてください。
回答の根拠となったドキュメントのソース情報も可能な限り含めてください。
${LIBSQL_PROMPT}`,
  // ★ 生成モデル(LLM)：文脈を読んで文章で回答を書く「脳」。温度に従い確率的に単語を選ぶため
  //    出力は"非決定的"（言い回しが毎回変わりうる）。埋め込みモデルとは別種・別役割。
  //    この脳は自由に差し替え可能（精度重視なら高性能モデル、コスト重視なら Flash など）。
  model: "google/gemini-3.5-flash",
  // ragTool を「道具」として持たせる。エージェント(脳)が道具を使う、という関係。
  // 補足：このツールの中身を"別のエージェント"に差し替えると スーパーバイザーパターン になる。
  tools: { ragTool },
});
